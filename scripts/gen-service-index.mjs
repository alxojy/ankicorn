#!/usr/bin/env node
// Generates app/Cornhub/Backend/ServiceIndex.swift from rslib's generated dispatch code (backend.rs in the
// Rust build output). Service numbers come from the `Backend::run_service_method` match (odd family),
// method numbers from each `run_backend_<service>_service_method` match.
//
//   node scripts/gen-service-index.mjs [path/to/backend.rs]   write the table
//   node scripts/gen-service-index.mjs --check [path]         exit 1 if the committed table differs
// The path may also come from the BACKEND_RS environment variable; otherwise the first
// target/aarch64-apple-ios*/release/build/anki-*/out/backend.rs is used (also looked up in the sibling
// phase0-rslib-bridge worktree).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'app/Cornhub/Backend/ServiceIndex.swift');
const args = process.argv.slice(2);
const check = args.includes('--check');
const given = args.find((a) => !a.startsWith('--')) ?? process.env.BACKEND_RS;

function findBackendRs() {
  if (given) return given;
  const targets = [path.join(root, 'target'), path.join(root, '../phase0-rslib-bridge/target')];
  for (const t of targets) {
    if (!fs.existsSync(t)) continue;
    for (const triple of fs.readdirSync(t).filter((d) => d.startsWith('aarch64-apple-ios'))) {
      const build = path.join(t, triple, 'release/build');
      if (!fs.existsSync(build)) continue;
      for (const d of fs.readdirSync(build).filter((x) => x.startsWith('anki-'))) {
        const f = path.join(build, d, 'out/backend.rs');
        if (fs.existsSync(f)) return f;
      }
    }
  }
  fail('backend.rs not found; build the engine or pass its path / set BACKEND_RS');
}

function fail(msg) {
  console.error(`gen-service-index: ${msg}`);
  process.exit(1);
}

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const src = fs.readFileSync(findBackendRs(), 'utf8');

// The Backend dispatch is the last `pub fn run_service_method` (the earlier ones are the server family).
const dispatchAt = src.lastIndexOf('pub fn run_service_method');
if (dispatchAt < 0) fail('run_service_method not found');
const dispatch = src.slice(dispatchAt, src.indexOf('_ =>', dispatchAt));
const services = [...dispatch.matchAll(/^\s*(\d+) => self\.run_backend_(\w+)_service_method\(/gm)].map((m) => ({
  number: Number(m[1]),
  name: m[2],
}));
if (services.length < 10) fail(`parsed only ${services.length} services; generated code changed shape`);

for (const svc of services) {
  const start = src.indexOf(`pub(crate) fn run_backend_${svc.name}_service_method(`);
  if (start < 0) fail(`no dispatch function for ${svc.name}`);
  const matchAt = src.indexOf('match method {', start);
  const end = src.indexOf('_ =>', matchAt);
  const body = src.slice(matchAt, end);
  // Arms are `<n> => {` at one indentation level; the engine method is the first `Backend::<name>(`.
  const arms = body.split(/^\s{12}(?=\d+ => \{)/m).slice(1);
  svc.methods = arms.map((arm) => {
    const num = /^(\d+) => \{/.exec(arm);
    const name = /\bBackend\w*::(\w+)\(/.exec(arm);
    if (!num || !name) fail(`cannot parse a method arm in ${svc.name}`);
    return { number: Number(num[1]), name: name[1] };
  });
  if (svc.methods.length === 0) fail(`no methods parsed for ${svc.name}`);
}

let out = `// Generated by scripts/gen-service-index.mjs from rslib's backend.rs at the pinned Anki tag. Do not edit.
// Service numbers are the odd (Backend) family; method numbers are the order inside each service.

enum ServiceIndex {
`;
for (const svc of services) {
  out += `    enum ${camel(svc.name).replace(/^./, (c) => c.toUpperCase())} {\n        static let service: UInt32 = ${svc.number}\n`;
  for (const m of svc.methods) out += `        static let ${camel(m.name)}: UInt32 = ${m.number}\n`;
  out += '    }\n';
}
out += '}\n';

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== out) fail('ServiceIndex.swift is out of date; run scripts/gen-service-index.mjs');
  console.log('ServiceIndex.swift is up to date');
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, out);
  console.log(`wrote ${path.relative(root, outFile)} (${services.length} services)`);
}
